package app.steamgarage.domain

/**
 * Статус расходника (раздел «Статусы и уведомления» SPEC.md).
 * [urgency] задаёт порядок в списках: «Пора менять» → «Скоро» → «Нет данных» (требует внимания) → «Норма».
 */
enum class ItemStatus(val urgency: Int) {
    /** Нет ни одной записи замены. */
    NO_DATA(1),

    /** Остаток больше порогов. */
    OK(0),

    /** Остаток ≤ порога по км или по дням. */
    SOON(2),

    /** Остаток ≤ 0. */
    OVERDUE(3),
}
