package app.steamgarage.ui.components

import androidx.compose.runtime.staticCompositionLocalOf

/** Звуковые эффекты интерфейса (таблица «Звуковые эффекты» SPEC.md). */
enum class Sfx {
    /** Нажатие кнопки, вентиля, тумблера. */
    CLICK,

    /** Рычаг «Заменено»: ход рычага, храповик, колокольчик. */
    LEVER,

    /** Сохранение: шипение пара. */
    STEAM,

    /** Удаление: глухой лязг. */
    CLANG,

    /** Шаг цифры на барабане одометра. */
    DRUM_TICK,

    /** Начало синхронизации: раскрутка шестерён. */
    SYNC_START,

    /** Синхронизация прошла: двойной звонок. */
    SYNC_OK,

    /** Ошибка синхронизации: низкий гудок. */
    SYNC_ERROR,
}

/** Проигрыватель эффектов. Компоненты зовут его сами; реализация решает, звучать ли сейчас. */
fun interface SfxPlayer {
    fun play(sfx: Sfx)
}

/** По умолчанию — тишина (витрина, превью). Приложение подставляет настоящий проигрыватель. */
val LocalSfx = staticCompositionLocalOf { SfxPlayer { } }
